const assert = require('node:assert/strict');
const { launch, artifact, waitForProjectReady } = require('./browser.cjs');
(async () => {
  const browser = await launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1500, height: 1100 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.stack));
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.goto(process.env.STUDIO_URL);
    await page.locator('#startDesigner').click();
    await page.locator('#setupName').fill('Persona-Review');
    await page.locator('[data-designer-layout=free]').click();
    assert.match(await page.locator('#cw').getAttribute('aria-label'), /Artboard/);
    assert.match(await page.locator('[data-designer-layout=free]').textContent(), /Einzelne Entwürfe/);
    await page.locator('#designerSetupPreset').selectOption('1080x1440');
    assert.equal(await page.locator('#cw').inputValue(), '1080');
    assert.equal(await page.locator('#ch').inputValue(), '1440');
    await page.locator('#ct').fill('120');
    await page.locator('[data-designer-layout=slides]').click();
    assert.match(await page.locator('#cw').getAttribute('aria-label'), /Slide/);
    assert.equal(await page.locator('#ct').inputValue(), '120');
    await page.locator('#cw').fill('1200');
    assert.equal(await page.locator('#designerSetupPreset').inputValue(), 'custom');
    await page.locator('#designerSetupPreset').selectOption('1080x1350');
    await page.locator('#cn').fill('3');
    assert.equal(await page.locator('[data-designer-layout=slides]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('[data-designer-layout=free]').getAttribute('aria-pressed'), 'false');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.screenshot({ path: artifact('persona-designer-setup.png') });
    for (const theme of ['light', 'dark']) {
      await page.evaluate(t => studioSetTheme(t), theme);
      await page.setViewportSize({ width: 390, height: 844 });
      assert(await page.locator('#projectSetup').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
    }
    await page.setViewportSize({ width: 1500, height: 1100 });
    await page.evaluate(() => studioSetTheme('light'));
    await page.locator('#createProject').click();
    await waitForProjectReady(page);
    await page.evaluate(() => carouselObject('text', { text: 'Erster Absatz\nZweiter Absatz\nDritter Absatz', x: 100, y: 300, w: 600, h: 600, size: 60, color: '#202020' }));
    assert(await page.locator('.paragraph-scope').evaluate(el => !!el.nextElementSibling?.classList.contains('typo-tabs')));
    assert(await page.locator('[data-line-scope]').evaluate(el => el.closest('[data-typo-page]')?.dataset.typoPage === 'paragraph'));
    assert(!(await page.locator('[data-line-scope]').isVisible()));
    await page.locator('[data-paragraph-selection]').selectOption(['0', '2']);
    assert.match(await page.locator('[data-paragraph-count]').textContent(), /2 von 3/);
    await page.locator('[data-typo=paragraphSize]').fill('74');
    assert.deepEqual(await page.evaluate(() => carouselSelected()[0].textStyles.map(s => s?.size ?? null)), [74, undefined, 74]);
    await page.locator('[data-paragraph-all]').click();
    assert.match(await page.locator('[data-paragraph-count]').textContent(), /3 von 3/);
    assert(await page.locator('[data-paragraph-all]').isDisabled());
    await page.locator('#carouselProperties').evaluate(el => el.scrollTop = 0);
    await page.screenshot({ path: artifact('persona-text-panel.png') });
    await page.evaluate(() => { carouselSlideSelect(0); MKWSpreadUI.commit({ type: 'enable' }); MKWSpreadUI.commit({ type: 'join', ids: p.carousel.artboards.map(a => a.id) }); });
    const original = await page.evaluate(() => ({ ids: p.carousel.artboards.map(a => a.id), history: history.length, state: JSON.stringify(p.carousel) }));
    const drag = async (copy = false) => {
      const source = page.locator('.pages-thumb').first(), target = page.locator('.pages-thumb').nth(2);
      await source.scrollIntoViewIfNeeded();
      const a = await source.boundingBox(), b = await target.boundingBox();
      if (copy) await page.keyboard.down('Alt');
      await page.mouse.move(a.x + a.width / 2, a.y + 30);
      await page.mouse.down();
      await page.mouse.move(a.x + a.width / 2 + 12, a.y + 35, { steps: 4 });
      await page.mouse.move(b.x + b.width - 5, b.y + 35, { steps: 12 });
      await page.mouse.move(b.x + b.width - 4, b.y + 36);
    };
    await drag();
    assert.match(await page.locator('.pages-drag-feedback').textContent(), /Nach Seite 3 einfügen/);
    const feedbackBox = await page.locator('.pages-drag-feedback').boundingBox(), panelBox = await page.locator('#carouselProperties').boundingBox();
    assert(feedbackBox.y >= panelBox.y && feedbackBox.y + feedbackBox.height <= panelBox.y + panelBox.height, 'Drop result stays inside the visible inspector');
    await page.screenshot({ path: artifact('persona-page-drop.png') });
    await page.keyboard.press('Escape'); await page.mouse.up();
    assert.deepEqual(await page.evaluate(() => ({ ids: p.carousel.artboards.map(a => a.id), history: history.length, state: JSON.stringify(p.carousel) })), original);
    await drag(); await page.mouse.up();
    assert.deepEqual(await page.evaluate(() => p.carousel.artboards.map(a => a.id)), [original.ids[1], original.ids[2], original.ids[0]]);
    await page.evaluate(() => undo());
    await drag(true);
    assert.match(await page.locator('.pages-drag-feedback').textContent(), /Kopie: Nach Seite 3/);
    await page.mouse.up(); await page.keyboard.up('Alt');
    assert.equal(await page.evaluate(() => p.carousel.n), 4);
    await page.evaluate(() => undo());
    assert.equal(await page.evaluate(() => p.carousel.n), 3);
    await page.addScriptTag({ path: require.resolve('axe-core/axe.min.js') });
    assert.deepEqual(await page.evaluate(async () => (await axe.run('#carouselSidebar')).violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))), []);
    assert.deepEqual(errors, []);
    console.log('PASS described Designer layouts, presets/manual sizes, responsive setup, paragraph scope/tab ordering, real drag target feedback/reorder/copy/cancel/undo and axe');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
