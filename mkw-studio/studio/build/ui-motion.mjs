import { writeFile } from "node:fs/promises";

// Equal angular samples let browsers interpolate our lightweight web shapes.
// These are an adaptation of Material Expressive, not Android's polygon engine.
const count = 72;
const cookie = (lobes, depth) => (t) => 0.86 + depth * Math.cos(lobes * t);
const ellipse = (a, b) => (t) =>
  (a * b) / Math.hypot(b * Math.cos(t), a * Math.sin(t));
const pentagon = (t) => {
  const sector = (Math.PI * 2) / 5;
  const local = ((t + sector / 2 + Math.PI * 2) % sector) - sector / 2;
  return (0.9 * Math.cos(Math.PI / 5)) / Math.cos(local);
};
const shapes = [
  cookie(12, 0.09),
  cookie(9, 0.08),
  pentagon,
  ellipse(0.96, 0.55),
  cookie(8, 0.11),
  cookie(4, 0.12),
  ellipse(0.94, 0.78),
];
function polygon(shape) {
  const radii = Array.from({ length: count }, (_, i) =>
    shape((i * Math.PI * 2) / count),
  );
  return `polygon(${radii
    .map((radius, i) => {
      const t = (i * Math.PI * 2) / count - Math.PI / 2;
      const smooth =
        (radii[(i + count - 1) % count] + 2 * radius + radii[(i + 1) % count]) /
        4;
      return `${(50 + 48 * smooth * Math.cos(t)).toFixed(2)}% ${(50 + 48 * smooth * Math.sin(t)).toFixed(2)}%`;
    })
    .join(", ")})`;
}
export async function writeMotionShapes() {
  const css = [
    "/* Generated by build/ui-motion.mjs. Do not edit sampled shapes by hand. */",
    `:root { --studio-loading-shape: ${polygon(shapes[0])}; }`,
    "@keyframes studio-loading-morph {",
    ...[...shapes, shapes[0]].map(
      (shape, i) =>
        `  ${((i / shapes.length) * 100).toFixed(5)}% { clip-path: ${polygon(shape)}; }`,
    ),
    "}",
    "@keyframes studio-loading-rotate { to { rotate: 360deg; } }",
  ];
  await writeFile(
    new URL("../static/ui-motion-shapes.css", import.meta.url),
    css.join("\n") + "\n",
  );
}
