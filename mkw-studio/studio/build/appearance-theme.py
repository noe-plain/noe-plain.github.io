"""Generate scoped light UI colours from the shared editor styles (no runtime dependency)."""
from pathlib import Path
import colorsys
import re

root = Path(__file__).resolve().parent.parent
overrides = {
    '#15191f': '#e9edf2', '#151a22': '#e9edf2', '#16191e': '#e9edf2',
    '#1e232b': '#ffffff', '#20252e': '#ffffff', '#20242b': '#ffffff',
    '#242a34': '#ffffff', '#222832': '#ffffff', '#252b35': '#f7f9fc',
    '#282d36': '#ffffff', '#3b424e': '#cbd3e0', '#353e50': '#e9effa',
    '#191f2a': '#f5f7fb', '#171d26': '#ffffff', '#252c37': '#ffffff',
    '#48556c': '#ccd5e5', '#303c54': '#e8eefc', '#4a5c7e': '#c0cdea', '#303f60': '#e8eefc',
    '#a4b5ff': '#3659c6', '#b5c4ff': '#3659c6',
    '#edf2ff': '#182b49', '#eef3ff': '#182b49', '#e3e7ef': '#233550',
}
def colour(match):
    value = match.group().lower()
    raw = value[1:]
    if len(raw) in (3, 4):
        raw = ''.join(char * 2 for char in raw)
    key = '#' + raw[:6]
    if key in overrides:
        return overrides[key] + raw[6:]
    r, g, b = (int(raw[i:i+2], 16) / 255 for i in (0, 2, 4))
    h, lightness, saturation = colorsys.rgb_to_hls(r, g, b)
    r, g, b = colorsys.hls_to_rgb(h, max(.07, min(.98, 1 - lightness)), saturation * .7)
    return '#' + ''.join(f'{round(channel * 255):02x}' for channel in (r, g, b)) + raw[6:]

def rules(css):
    output = []
    index = 0
    while index < len(css):
        start = css.find('{', index)
        if start == -1:
            break
        selector = css[index:start].strip()
        depth, end = 1, start + 1
        while depth:
            if css[end] == '{': depth += 1
            if css[end] == '}': depth -= 1
            end += 1
        body = css[start+1:end-1]
        index = end
        if selector.startswith(('@media', '@supports')):
            content = rules(body)
            if content: output.append(selector + '{' + content + '}')
        elif not selector.startswith('@'):
            selectors = [item.strip() for item in selector.split(',')]
            # Logo swatches represent the artwork colours, rather than the editor theme.
            selectors = [item for item in selectors if '.logo-choice' not in item]
            declarations = []
            for declaration in body.split(';'):
                if ':' not in declaration: continue
                prop, value = declaration.split(':', 1)
                if not (prop.startswith('--') or prop.strip() in ['color','background','background-color','background-image','box-shadow','text-shadow','border','border-color','border-top','border-top-color','border-right','border-right-color','border-bottom','border-bottom-color','border-left','border-left-color','outline','outline-color','fill','stroke','accent-color','scrollbar-color','filter']): continue
                value = re.sub(r'(?<![\w-])white\b', '#ffffff', value)
                value = re.sub(r'(?<![\w-])black\b', '#000000', value)
                declarations.append(prop + ':' + re.sub(r'#[0-9a-fA-F]{3,8}\b', colour, value))
            if selectors and declarations:
                scoped = [item.replace(':root', 'html[data-theme=light]') if ':root' in item else 'html[data-theme=light] ' + item for item in selectors]
                output.append(','.join(scoped) + '{' + ';'.join(declarations) + '}')
    return '\n'.join(output)

result = ['/* Generated by build/appearance-theme.py; canvas artwork and logo swatches stay unchanged. */', 'html[data-theme=light]{color-scheme:light}html[data-theme=light] :is(input,select,textarea){color-scheme:light}']
for name in ['style.css', 'upgrade.css', 'carousel.css', 'workspace-ui.css', 'chrome.css']:
    css = re.sub(r'/\*.*?\*/', '', (root / 'static' / name).read_text(), flags=re.S)
    result.append(rules(css))
result.append('html[data-theme=light] .studio-commandbar{box-shadow:0 8px 28px #24344c1f}')
(root / 'static' / 'appearance.css').write_text('\n'.join(result) + '\n')
