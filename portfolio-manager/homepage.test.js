const studio = require('./studio');
const model = require('../portfolio/home-hero-model');

test('Hero model: seven unique links, both legacy image fields, hostile paths and limits', () => {
    const rows = Array.from({ length: 8 }, (_, i) => ({ id: 'project-' + i, title: '<b>Project ' + i + '</b>', 'hero-image': '../../images/example.jpg' }));
    const catalog = model.catalog({ design: rows, video: [{ id: 'movie', title: 'Movie', heroImage: '../images/movie.jpg' }], illustration: [{ id: 'lamaLami', title: 'Lama', 'hero-image': '../../images/lama.svg' }] });
    const config = { enabled: true, motion: 18, projects: rows.slice(0, 7).map(p => ({ type: 'design', id: p.id })) };
    const normalized = model.normalize(config, catalog);
    assert.equal(model.resolve(normalized, catalog).length, 7);
    assert.equal(catalog[0].title, 'Project 0');
    assert.equal(model.text('Me&shy;dien&#173;design&#xad;'), 'Me\u00addien\u00addesign\u00ad');
    assert.equal(model.normalize({ ...config, title: 'Me&shy;dien' }, catalog).title, 'Me&shy;dien');
    assert.equal(model.catalog({ design: [{ id: 'shy', title: 'Me&shy;dien', 'hero-image': '../../images/example.jpg' }] })[0].title, 'Me\u00addien');
    assert.equal(catalog.find(p => p.type === 'video').href, 'portfolio/projekte/video.html?project=movie');
    assert.equal(catalog.find(p => p.type === 'video').image, 'images/movie.jpg');
    assert.equal(catalog.find(p => p.type === 'illustration').id, 'lamaLami');
    assert.throws(() => model.normalize({ ...config, projects: [...config.projects, { type: 'design', id: 'project-7' }] }, catalog));
    assert.throws(() => model.normalize({ ...config, projects: [config.projects[0], config.projects[0]] }, catalog));
    for (const motion of [-1, 33, NaN, '18']) assert.throws(() => model.normalize({ ...config, motion }, catalog));
    for (const image of ['javascript:alert(1)', 'https://evil.invalid/a.jpg', 'images/../secret.jpg', 'images/raw/private.jpg', 'images/%252e%252e/private.jpg', 'images/test.jpg?x=1']) assert.equal(model.imagePath(image), null);
    assert.throws(() => model.normalize({ ...config, projects: [{ type: '__proto__', id: 'x' }] }, catalog));
    assert.throws(() => model.normalize({ enabled: true, motion: 0, projects: [] }, catalog));
    assert.deepEqual(model.resolve({ projects: [{ type: 'design', id: 'removed' }] }, catalog), []);
});

test('Homepage API: exact previews, revisions, invalid input, bounded changes and localhost protection', async t => {
    const root = await fs.mkdtemp(path.join(os.tmpdir(), 'noe-home-test-'));
    await fs.mkdir(path.join(root, 'portfolio/projekte'), { recursive: true }); await fs.mkdir(path.join(root, 'images'));
    await fs.writeFile(path.join(root, 'images/example.jpg'), 'test image');
    const original = '<html><body><header>unchanged</header><div id="about"><!-- home:about:start --><h2>About</h2><!-- home:about:end --></div><footer>unchanged</footer></body></html>';
    await fs.writeFile(path.join(root, 'index.html'), original);
    for (const [type, source] of Object.entries(model.sources)) await fs.writeFile(path.join(root, 'portfolio/projekte', source.file), JSON.stringify(type === 'design' ? [{ id: 'example', title: 'Example', 'hero-image': '../../images/example.jpg' }] : []));
    await fs.writeFile(path.join(root, 'lebenslauf.json'), '[]');
    const app = express(); studio(app, root);
    const server = await new Promise(resolve => { const value = app.listen(0, '127.0.0.1', () => resolve(value)); });
    t.after(async () => { await new Promise(resolve => server.close(resolve)); await fs.rm(root, { recursive: true, force: true }); });
    const origin = 'http://127.0.0.1:' + server.address().port;
    const token = (await (await fetch(origin + '/api/studio/session')).json()).token;
    async function request(url, body, method = 'PUT', extra = {}) {
        const response = await fetch(origin + url, body === undefined ? {} : { method, headers: { Origin: origin, 'Content-Type': 'application/json', 'X-CMS-Token': token, ...extra }, body: JSON.stringify(body) });
        return { status: response.status, body: await response.json() };
    }
    const hero = (await request('/api/studio/home/hero')).body;
    const config = { enabled: true, motion: 18, projects: [{ type: 'design', id: 'example', fit: 'contain' }] };
    assert.equal((await request('/api/studio/home/hero', { data: config, revision: hero.revision }, 'PUT', { 'X-CMS-Token': '' })).status, 403);
    assert.equal((await request('/api/studio/home/hero', { data: config, revision: hero.revision }, 'PUT', { Origin: 'https://evil.invalid' })).status, 403);
    assert.equal((await request('/api/studio/preview', { id: 'hero-test', homeSection: 'hero', data: config }, 'POST')).status, 200);
    assert.equal((await request('/preview/hero-test/portfolio/home-hero.json')).body.projects[0].fit, 'contain');
    await assert.rejects(fs.readFile(path.join(root, 'portfolio/home-hero.json')));
    const saved = await request('/api/studio/home/hero', { data: config, revision: hero.revision }); assert.equal(saved.status, 200);
    assert.equal((await request('/api/studio/home/hero', { data: config, revision: hero.revision })).status, 409);
    const before = await fs.readFile(path.join(root, 'portfolio/home-hero.json'), 'utf8');
    for (const projects of [[...config.projects, ...config.projects], [{ type: 'design', id: 'missing' }], [{ type: 'design', id: 'example', image: 'images/missing.jpg' }]]) assert.equal((await request('/api/studio/home/hero', { data: { ...config, projects }, revision: saved.body.revision })).status, 400);
    assert.equal(await fs.readFile(path.join(root, 'portfolio/home-hero.json'), 'utf8'), before);
    const about = (await request('/api/studio/home/about')).body;
    assert.equal((await request('/api/studio/preview', { id: 'about-test', homeSection: 'about', data: '<h2>Draft</h2>' }, 'POST')).status, 200);
    assert.match(await (await fetch(origin + '/preview/about-test/index.html')).text(), /<h2>Draft<\/h2>/);
    assert.equal(await fs.readFile(path.join(root, 'index.html'), 'utf8'), original);
    assert.equal((await request('/api/studio/home/about', { data: '<h2>Saved</h2>', revision: about.revision })).status, 200);
    const after = await fs.readFile(path.join(root, 'index.html'), 'utf8');
    assert.match(after, /<header>unchanged<\/header>/); assert.match(after, /<footer>unchanged<\/footer>/);
    assert.equal((await request('/api/studio/home/about', { data: '<h2>Stale</h2>', revision: about.revision })).status, 409);
    const resume = (await request('/api/studio/home/resume')).body;
    const entries = [{ year: '2026', title: 'Designer', company: 'Studio', description: 'Text &shy; remains.' }];
    assert.equal((await request('/api/studio/preview', { id: 'resume-test', homeSection: 'resume', data: entries }, 'POST')).status, 200);
    assert.deepEqual((await request('/preview/resume-test/lebenslauf.json')).body, entries);
    assert.equal(await fs.readFile(path.join(root, 'lebenslauf.json'), 'utf8'), '[]');
    assert.equal((await request('/api/studio/home/resume', { data: [{ ...entries[0], title: '<img onerror=alert(1)>' }], revision: resume.revision })).status, 400);
    assert.equal((await request('/api/studio/home/resume', { data: entries, revision: resume.revision })).status, 200);
    assert.equal((await request('/api/studio/home/resume', { data: entries, revision: resume.revision })).status, 409);
    assert.equal((await request('/api/studio/preview', { id: 'bad-test', homeSection: '__proto__', data: {} }, 'POST')).status, 400);
});
