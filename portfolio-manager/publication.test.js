'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const express = require('express');
const sharp = require('sharp');

test('Full CMS publication: encrypted delivery first, pinned catalog, metadata reuse and push-only recovery', async t => {
    const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'noe-publication-'));
    const root = path.join(temp, 'site'), remote = path.join(temp, 'remote.git'); fs.mkdirSync(root);
    fs.writeFileSync(path.join(root, '.gitignore'), 'portfolio-manager/.client-galleries/\n');
    fs.writeFileSync(path.join(root, 'index.html'), '<html><body>Design remains unchanged</body></html>');
    const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
    execFileSync('git', ['init', '--bare', remote], { stdio: 'ignore' });
    git('init', '-b', 'main'); git('config', 'user.name', 'CMS Test'); git('config', 'user.email', 'test@example.invalid');
    const github = 'https://github.com/noe-audit/site.git';
    git('config', 'url.' + remote + '.insteadOf', github); git('remote', 'add', 'origin', github);
    git('add', '.'); git('commit', '-m', 'Initial'); git('push', '-u', 'origin', 'main');
    const app = express(); require('./studio')(app, root);
    const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
    t.after(async () => { await app.locals.closePreview(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); fs.rmSync(temp, { recursive: true, force: true }); });
    const origin = 'http://127.0.0.1:' + server.address().port;
    const token = (await (await fetch(origin + '/api/studio/session')).json()).token;
    const headers = { Origin: origin, 'X-CMS-Token': token };
    const send = (url, value) => fetch(origin + url, { method: 'POST', headers: { ...headers, 'Content-Type': 'application/json' }, body: JSON.stringify(value) });
    let response = await send('/api/studio/clients', { title: 'Audit-Veranstaltung', password: 'Ein-langes-Testpasswort' });
    assert.equal(response.status, 200); let event = await response.json();
    const jpeg = await sharp({ create: { width: 20, height: 16, channels: 3, background: '#ddcfe6' } }).jpeg().toBuffer();
    const form = new FormData(); form.append('revision', event.revision); form.append('images', new Blob([jpeg], { type: 'image/jpeg' }), 'Foto.jpg');
    response = await fetch(origin + '/api/studio/clients/' + event.id + '/upload', { method: 'POST', headers, body: form });
    assert.equal(response.status, 200); event = await response.json();
    const state = await (await fetch(origin + '/api/studio/git')).json();
    assert.deepEqual(state.changes.map(c => c.file), ['portfolio/kunden/catalog.json']);
    response = await send('/api/publish', { signature: state.signature, files: ['portfolio/kunden/catalog.json'], message: 'Publish gallery' });
    assert.equal(response.status, 200, await response.clone().text());
    const customerPreview = await (await send('/api/studio/preview', { id: 'customer-preview', file: 'kunden.html', html: '<html><body>Customer preview</body></html>' })).json();
    const previewCatalog = await (await fetch(customerPreview.prefix + 'portfolio/kunden/catalog.json')).json();
    assert.ok(previewCatalog[0].deliveryBase.startsWith('/preview/customer-preview/'));
    assert.equal((await fetch(new URL(previewCatalog[0].bundle, new URL(previewCatalog[0].deliveryBase, customerPreview.prefix)))).status, 200);
    const firstData = execFileSync('git', ['--git-dir', remote, 'rev-parse', 'customer-delivery'], { encoding: 'utf8' }).trim();
    const catalog = JSON.parse(execFileSync('git', ['--git-dir', remote, 'show', 'main:portfolio/kunden/catalog.json'], { encoding: 'utf8' }));
    assert.ok(catalog[0].deliveryBase.includes('/' + firstData + '/'));
    assert.equal((await (await fetch(origin + '/api/studio/clients')).json())[0].publication, 'published');
    const publishedFiles = git('ls-tree', '-r', '--name-only', firstData).split('\n');
    assert.equal(publishedFiles.length, 4); assert.ok(publishedFiles.every(file => file.endsWith('.bin')));
    assert.ok(!git('ls-tree', '-r', '--name-only', 'HEAD').includes('.client-galleries'));
    response = await send('/api/studio/clients', { ...event, images: event.images.map(image => image.id), description: 'Geänderte Nachricht', password: '' });
    assert.equal(response.status, 200); event = await response.json();
    const hook = path.join(remote, 'hooks/pre-receive');
    fs.writeFileSync(hook, '#!/bin/sh\nwhile read old new ref; do\n[ "$ref" != "refs/heads/main" ] || exit 1\ndone\n', { mode: 0o755 });
    const secondState = await (await fetch(origin + '/api/studio/git')).json();
    response = await send('/api/publish', { signature: secondState.signature, files: ['portfolio/kunden/catalog.json'], message: 'Update gallery message' });
    assert.equal(response.status, 500); assert.match((await response.json()).error, /Commit wurde lokal erstellt/);
    const secondData = execFileSync('git', ['--git-dir', remote, 'rev-parse', 'customer-delivery'], { encoding: 'utf8' }).trim();
    const delta = git('diff-tree', '--no-commit-id', '--name-only', '-r', firstData, secondData).split('\n');
    assert.equal(delta.length, 1); assert.ok(delta[0].endsWith('/gallery.bin'));
    assert.equal((await (await fetch(origin + '/api/studio/clients')).json())[0].publication, 'pending');
    fs.unlinkSync(hook);
    const retryState = await (await fetch(origin + '/api/studio/git?refresh=1')).json(); assert.equal(retryState.ahead, 1);
    response = await send('/api/publish', { signature: retryState.signature, files: [], message: '' });
    assert.equal(response.status, 200); assert.equal((await response.json()).state.ahead, 0);
    assert.equal(execFileSync('git', ['--git-dir', remote, 'rev-parse', 'customer-delivery'], { encoding: 'utf8' }).trim(), secondData);
    assert.equal((await (await fetch(origin + '/api/studio/clients')).json())[0].publication, 'published');
    assert.equal(fs.readFileSync(path.join(root, 'index.html'), 'utf8'), '<html><body>Design remains unchanged</body></html>');
});

test('Existing encrypted galleries migrate without original JPEGs or re-encryption', async t => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'noe-legacy-encryption-'));
    const id = crypto.randomUUID(), release = crypto.randomUUID(), image = crypto.randomUUID(), key = crypto.randomBytes(32);
    const privateDir = path.join(root, 'portfolio-manager/.client-galleries'), publicDir = path.join(root, 'portfolio/kunden/data');
    fs.mkdirSync(privateDir, { recursive: true }); fs.mkdirSync(path.join(publicDir, id, release), { recursive: true });
    const seal = require('./client-galleries').seal;
    const item = { id: image, name: 'Legacy.jpg', width: 20, height: 10, size: 100, full: image + '-full.bin', preview: image + '-preview.bin', thumb: image + '-thumb.bin' };
    for (const kind of ['full', 'preview', 'thumb']) fs.writeFileSync(path.join(publicDir, id, release, item[kind]), seal(Buffer.from('existing ' + kind), key));
    const manifest = seal(Buffer.from(JSON.stringify({ title: 'Legacy', images: [item] })), key);
    fs.writeFileSync(path.join(publicDir, id, release, 'gallery.bin'), manifest);
    const { full, preview, thumb, ...metadata } = item;
    const event = { id, release, title: 'Legacy', slug: 'legacy', active: true, revision: 'old', key: key.toString('base64'), salt: crypto.randomBytes(16).toString('base64'), images: [metadata] };
    fs.writeFileSync(path.join(privateDir, 'events.json'), JSON.stringify([event]));
    const app = express(); require('./studio')(app, root);
    const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
    t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); fs.rmSync(root, { recursive: true, force: true }); });
    const origin = 'http://127.0.0.1:' + server.address().port, token = (await (await fetch(origin + '/api/studio/session')).json()).token;
    const response = await fetch(origin + '/api/studio/clients', { method: 'POST', headers: { Origin: origin, 'X-CMS-Token': token, 'Content-Type': 'application/json' }, body: JSON.stringify({ id, revision: 'old', title: 'New message', password: '' }) });
    assert.equal(response.status, 200); const updated = await response.json();
    assert.deepEqual(fs.readFileSync(path.join(publicDir, id, release, 'gallery.bin')), manifest);
    assert.ok(!fs.existsSync(path.join(privateDir, 'delivery', id, 'assets')));
    const source = await fetch(origin + '/portfolio/kunden/data/' + id + '/' + release + '/' + item.full);
    assert.equal(source.status, 200);
    const newManifest = await fetch(origin + '/portfolio/kunden/data/' + id + '/' + JSON.parse(fs.readFileSync(path.join(privateDir, 'events.json')))[0].release + '/gallery.bin');
    assert.equal(newManifest.status, 200); assert.equal(updated.images.length, 1);
});
